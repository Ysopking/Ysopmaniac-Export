/// Locale-Katalog: Alle Laender (ISO 3166-1 alpha-2) + Top-6-Sprachen.
///
/// Sprachen: Deutsch, Englisch, Mandarin, Spanisch, Arabisch, Hindi
/// Laender:  Alle UN-Mitgliedsstaaten + wichtige Territorien (sortiert nach
///           deutschem Namen).

class LocaleLanguage {
  final String code;        // BCP-47 / ISO 639-1
  final String nativeLabel; // In der Sprache selbst
  final String germanLabel; // Deutsches Etikett
  final String flag;        // Flag-Emoji des Hauptlandes
  final bool isRtl;         // Rechts-nach-Links?
  const LocaleLanguage({
    required this.code,
    required this.nativeLabel,
    required this.germanLabel,
    required this.flag,
    this.isRtl = false,
  });
}

class LocaleCountry {
  final String code;  // ISO 3166-1 alpha-2 (lowercase)
  final String flag;  // Flag-Emoji
  final String label; // Deutscher Name
  const LocaleCountry({required this.code, required this.flag, required this.label});
}

